// Converts the exported Google Sheets HTML in ../tester-gear into the JSON files
// the mod reads. Re-run this whenever the sheet is updated:
//
//     node tools/build-data.js
//
// Expects (all from File -> Download -> Web Page in Google Sheets):
//   data.html                  - DUNGEON | DAMAGE TYPE | CLASS | ... | OUTPUT  (per-slot ids in the trailing columns)
//   dungeons full list.html    - id | name
//   ToT testing dungeons.html  - id | name | min ilvl | NOTES
//   key.html                   - id | name of item
'use strict';

const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'tester-gear');
const OUT = path.join(__dirname, '..');

// ---------- Google Sheets HTML -> rows of text ----------
function parseGoogleHtml(file) {
	const html = fs.readFileSync(file, 'utf8');
	const tb = html.match(/<tbody>([\s\S]*?)<\/tbody>/);
	if (!tb) throw new Error(`no <tbody> in ${file}`);

	return tb[1].split(/<tr[^>]*>/).slice(1).map(raw => {
		const cells = [];
		const re = /<td[^>]*>([\s\S]*?)<\/td>/g;
		let m;
		while ((m = re.exec(raw)) !== null) {
			cells.push(m[1]
				.replace(/<[^>]+>/g, ' ')
				.replace(/&nbsp;/g, ' ')
				.replace(/&amp;/g, '&')
				.replace(/&lt;/g, '<')
				.replace(/&gt;/g, '>')
				.replace(/&quot;/g, '"')
				.replace(/&#39;/g, "'")
				.replace(/\s+/g, ' ')
				.trim());
		}
		while (cells.length && cells[cells.length - 1] === '') cells.pop();
		return cells;
	});
}

const num = s => (/^-?\d+$/.test(s) ? parseInt(s, 10) : null);
const SMALL = ['of', 'the', 'and', 'in', 'on', 'to'];
const titleCase = s => String(s).toLowerCase().split(/(\s+)/).map((w, i) => {
	if (/^\s+$/.test(w) || SMALL.indexOf(w) !== -1 && i > 0) return w;
	return w.charAt(0).toUpperCase() + w.slice(1);
}).join('');

// ---------- gear sets (data.html) ----------
const SLOT_NAMES = ['weapon', 'chest', 'gloves', 'footwear', 'necklace', 'ring', 'ring', 'earring', 'earring', 'belt', 'brooch'];
const gearRows = parseGoogleHtml(path.join(SRC, 'data.html'));
const sets = [];
const seen = {};
gearRows.slice(1).forEach(r => {
	const dungeon = r[0], damageType = r[1], cls = r[2], output = r[4];
	if (!dungeon || !damageType || !cls || !output || output.indexOf('@makeitems') === -1) return;

	// "/@makeitems <id> ... <qty>" - the trailing number is the quantity
	const tokens = output.replace(/^\/@?/, '').replace(/^\w+\s*/, '').split(/\s+/).filter(t => t);
	const qty = num(tokens.pop());
	const items = tokens.map(num).filter(v => v !== null);
	if (!items.length || qty === null) return;

	const key = `${dungeon}|${damageType}|${cls}`;
	if (seen[key]) return;
	seen[key] = 1;

	sets.push({
		name: `${titleCase(dungeon)} - ${titleCase(damageType)} ${titleCase(cls)}`,
		dungeon: titleCase(dungeon),
		damageType: titleCase(damageType),
		class: titleCase(cls),
		items: items,
		qty: qty
	});
});

// Filters = distinct values actually present, in a stable order
const distinct = key => {
	const out = [];
	sets.forEach(s => { if (out.indexOf(s[key]) === -1) out.push(s[key]); });
	return out.sort();
};

fs.writeFileSync(path.join(OUT, 'gearsets.json'), JSON.stringify({
	_note: 'Generated by tools/build-data.js from tester-gear/data.html. The menu builds /@makeitems <items...> <qty> from the selected set.',
	slotNames: SLOT_NAMES,
	filters: [
		{ key: 'dungeon', label: 'Dungeon' },
		{ key: 'damageType', label: 'Damage type' },
		{ key: 'class', label: 'Class' }
	],
	sets: sets
}, null, 1) + '\n');
console.log(`gearsets.json: ${sets.length} sets`);

// ---------- dungeons (dungeons full list.html + notes from ToT sheet) ----------
const notes = {};
const totRows = parseGoogleHtml(path.join(SRC, 'ToT testing dungeons.html'));
totRows.slice(3).forEach(r => {                       // skip title + "/@enter_dungeon" header rows
	const id = num(String(r[0] || '').trim());
	if (id === null) return;
	if (r[1]) notes[id] = { name: String(r[1]).trim(), note: (r[3] || '').trim() || undefined };
});

const dungeonRows = parseGoogleHtml(path.join(SRC, 'dungeons full list.html'));
const dungeons = [];
const seenDungeon = {};
dungeonRows.slice(1).forEach(r => {                    // skip the "id | name" header
	const id = num(String(r[0] || '').trim());
	const name = (r[1] || '').trim();
	if (id === null || !name || seenDungeon[id]) return;
	seenDungeon[id] = 1;
	dungeons.push(notes[id]
		? { name: notes[id].name, contId: id, note: notes[id].note }
		: { name: name, contId: id });
});
dungeons.sort((a, b) => a.name.localeCompare(b.name));

fs.writeFileSync(path.join(OUT, 'dungeons.json'), JSON.stringify({
	_note: 'Generated by tools/build-data.js from tester-gear. contId is the zone id shown in the menu header; "Save current zone" adds to this file in-game.',
	dungeons: dungeons
}, null, 1) + '\n');
console.log(`dungeons.json: ${dungeons.length} dungeons (${Object.keys(notes).length} notes merged)`);

// ---------- item id -> name key (key.html) ----------
const keyRows = parseGoogleHtml(path.join(SRC, 'key.html'));
const key = {};
keyRows.forEach(r => {
	const id = num(String(r[2] || '').trim());
	const name = (r[3] || '').trim();
	if (id === null || !name) return;
	key[id] = name;
});

fs.writeFileSync(path.join(OUT, 'key.json'), JSON.stringify(key, null, 1) + '\n');
console.log(`key.json: ${Object.keys(key).length} item names`);
